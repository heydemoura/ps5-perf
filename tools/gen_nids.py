#!/usr/bin/env python3
"""Generate src NID table: NID (11 chars) -> symbol name, from the symbol
names exported by the PS5 payload SDK's stub libraries."""
import base64, hashlib, os, shutil, struct, subprocess, sys

SALT = bytes.fromhex("518d64a635ded8c1e6b039b1c3e55230")

def nid(name):
    d = hashlib.sha1(name.encode() + SALT).digest()
    v = struct.unpack("<Q", d[:8])[0]
    return base64.b64encode(struct.pack(">Q", v)).decode().replace("/", "-")[:11]

def main():
    sdk, out = sys.argv[1], sys.argv[2]
    nm = shutil.which("llvm-nm") or os.path.join(sdk, "bin", "prospero-nm")
    names = set()
    libdir = os.path.join(sdk, "target", "lib")
    for fn in sorted(os.listdir(libdir)) if os.path.isdir(libdir) else []:
        if fn.endswith(".so"):
            r = subprocess.run([nm, "-D", "--defined-only", os.path.join(libdir, fn)],
                               capture_output=True, text=True)
            names.update(l.split()[-1] for l in r.stdout.splitlines() if len(l.split()) >= 3)
    table = sorted((nid(n), n) for n in names)
    with open(out, "w") as f:
        f.write("/* generated by tools/gen_nids.py - do not edit */\n#include <string.h>\n")
        f.write("#include <stdlib.h>\n\nstatic const char nid_keys[][11] = {\n")
        for k, _ in table:
            f.write('  {%s},\n' % ",".join("'%s'" % (c if c != "'" else "\\'") for c in k))
        f.write("};\n\nstatic const char *const nid_names[] = {\n")
        for _, n in table:
            f.write('  "%s",\n' % n)
        f.write("};\n\n")
        f.write("static int cmp(const void *a, const void *b) { return memcmp(a, b, 11); }\n\n"
                "const char *\nnid_lookup(const char *nid) {\n"
                "  const char (*k)[11] = bsearch(nid, nid_keys, sizeof(nid_keys) / 11, 11, cmp);\n"
                "  return k ? nid_names[k - nid_keys] : NULL;\n}\n")
    print("gen_nids: %d symbols" % len(table))

main()
